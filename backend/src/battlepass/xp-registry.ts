/**
 * Реестр источников XP — единственный источник правды о том, за что дают опыт.
 * Приём тот же, что у реестра уведомлений: добавить игру значит добавить
 * запись, а не править четыре файла.
 *
 * Опыт — за то, что человек сделал сам (владелец 2026-10-17: «за любую
 * активность на платформе, кроме afk»): открыл позицию, сыграл партию,
 * поставил, завёл свои теги. Не за время на странице, не за опрос данных и не
 * за то, что случилось без него, — сработавший лимит, стоп, ход по таймауту.
 *
 * Числа живут здесь, форма формулы — по месту вызова: контекст («сколько было
 * участников», «какое место») знает только вызывающий, и тащить его сюда
 * значило бы описывать в реестре каждую будущую игру заранее.
 */

export type XpSource =
  | 'game.tournament'
  | 'game.backtest'
  | 'game.table'
  | 'game.jetpack'
  | 'game.race'
  | 'trade.open'
  | 'journal.setup'
  | 'journal.tag';

export interface XpSourceDef {
  /** Заголовок для API; фронт переводит по ключу с откатом на него. */
  title: string;
  /** Начисляется ли сейчас. false — запись есть, начисление выключено. */
  enabled: boolean;
  /** База начисления за одно событие. */
  base: number;
  /** Надбавка за каждого обойдённого соперника. Есть только у турнира. */
  perOpponent?: number;
  /**
   * Потолок XP из этого источника за сутки UTC. null — потолка нет.
   *
   * Потолок здесь не украшение: турнир заводится на два своих аккаунта с
   * нулевым взносом, позиция открывается и закрывается за секунду, раунд
   * джетпака идёт каждые полминуты. Без потолка трек набивается за вечер и
   * перестаёт что-либо значить. Поэтому потолок есть у каждого источника,
   * который даёт опыт.
   */
  dailyCap: number | null;
}

