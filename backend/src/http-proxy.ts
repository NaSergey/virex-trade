import { NestExpressApplication } from '@nestjs/platform-express';

/**
 * Настоящий адрес посетителя за прокси. Без этого `req.ip` — адрес ближайшего
 * прокси, общий для всех, и `ThrottlerGuard` считал весь сайт одним посетителем:
 * 30 заходов в минуту у всех сразу давали 429 на `/auth/refresh`, а этот ответ
 * клиент читает как конец сессии и выбрасывает вошедших.
 *
 * Один ход, а не `true`: `true` брал бы самый левый адрес заголовка, а его
 * присылает сам клиент, и перебор паролей обходился бы новым адресом на каждую
 * попытку. Самый правый дописывает наш внешний прокси (nginx хоста —
 * `$proxy_add_x_forwarded_for`, Caddy), а Next по дороге заголовок не трогает
 * (проверено на standalone-сборке), поэтому ход один и в варианте nginx → web → api.
 *
 * Держится на том, что `api` снаружи не виден (порт не опубликован): обратившийся
 * напрямую назвал бы любой адрес.
 */
const TRUSTED_PROXY_HOPS = 1;

export function trustProxy(app: NestExpressApplication): void {
  app.set('trust proxy', TRUSTED_PROXY_HOPS);
}
