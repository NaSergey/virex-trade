/**
 * Границы торгового турнира. Числа держатся здесь, а не в DTO и не в сервисе
 * по месту: их одновременно проверяет сервер и рисует форма создания, и две
 * копии одного правила разошлись бы молча.
 */

/**
 * Два участника — дуэль, тридцать — потолок арены (решение владельца
 * 2026-09-27; прежде было десять). У команд потолок тот же: 15 × 15.
 */
export const MIN_PLAYERS = 2;
export const MAX_PLAYERS = 30;

/**
 * Призовых мест арены — не больше десяти: доли фонда создатель вводит руками, и
 * двадцать девять полей долей никто не заполнит.
 */
export const MAX_WINNERS = 10;

/** Размер команды: от 2×2 до 15×15. Один на один — это дуэль, а не команды. */
export const TEAM_SIZE_MIN = 2;
export const TEAM_SIZE_MAX = 15;

/** Длительность турнира, минуты: час, четыре часа, день, три дня, неделя. */
export const DURATIONS_MIN = [60, 240, 1440, 4320, 10080] as const;

/** Сколько строк отдаёт общий список открытых турниров. */
export const PUBLIC_LIST_LIMIT = 50;

/** Сколько строк отдаёт рейтинг игры. */
export const RATING_LIMIT = 50;

/**
 * Запас после конца турнира, прежде чем подводить итоги: последняя минутка
 * должна закрыться и доехать с биржи. Без него финал считал бы по ещё
 * формирующейся свече, и цена итога у двух прогонов вышла бы разной.
 */
export const FINAL_GRACE_MS = 5_000;

/** Время старта — не раньше чем через минуту: отсчёт должен успеть кому-то показаться. */
export const START_MIN_LEAD_MS = 60_000;

/** И не позже чем через 30 дней: лобби на месяцы вперёд держит взносы без дела. */
export const START_MAX_LEAD_MS = 30 * 24 * 60 * 60_000;

/** Сколько сделок отдаёт лента идущих турниров. */
export const FEED_LIMIT = 50;
