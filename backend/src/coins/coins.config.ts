/**
 * Внутренняя валюта продукта — «монеты». Ими платят за участие в играх раздела
 * «Турниры», из них складывается призовой фонд. Целые числа без долей: делить
 * монету не на что, а дробный баланс потребовал бы тех же предосторожностей,
 * что и деньги доната, ничего не давая взамен.
 */

/**
 * Сколько монет даёт один USDT доната. Курс — константа кода, а не переменная
 * окружения: забытая переменная означала бы либо бесплатные монеты, либо
 * молча изменившуюся цену, а менять курс задним числом всё равно нельзя —
 * начисленное уже начислено.
 */
export const COINS_PER_USDT = 500;

/**
 * Сколько монет выдаётся новому аккаунту. Значение дублирует `@default(1000)` у
 * `User.coinBalance`: выдаёт их база (тогда их получают и уже заведённые
 * аккаунты, и новый — без шага в register, который можно забыть), а здесь оно
 * нужно текстам и тестам.
 */
export const STARTING_COINS = 1000;

/**
 * Сколько монет получает пригласивший, когда приглашённый по его ссылке
 * регистрируется. Начисляется по факту регистрации, а не по факту активности
 * приглашённого — см. `AuthService.register`.
 */
export const REFERRAL_BONUS_COINS = 1000;

/**
 * Потолок одной суммы в монетах: взноса в турнир и добавки в призовой фонд.
 * Не запрет тратить, а защита от опечатки в поле ввода — миллион монет это две
 * тысячи долларов доната, и турнир на такую сумму почти наверняка промах по
 * клавише, а не намерение.
 */
export const MAX_COINS_AMOUNT = 1_000_000;
