/**
 * Границы столов покера/блэкджека. Числа держатся здесь, а не в DTO и не в
 * сервисе по месту: их одновременно проверяет сервер и будущая форма
 * создания стола.
 */

export type GameType = 'blackjack' | 'poker';

/** Один живой игрок за столом — уже блэкджек; дуэль покера — от двух. */
export const SEATS_RANGE: Record<GameType, [min: number, max: number]> = {
  blackjack: [1, 7],
  poker: [2, 9],
};

export const GAME_TYPES = Object.keys(SEATS_RANGE) as GameType[];

/** Сколько строк отдаёт общий список открытых столов. */
export const PUBLIC_LIST_LIMIT = 50;

/**
 * Покер: большой блайнд задаёт создатель стола, малый — половина вниз. Меньше
 * двух — малый блайнд обнулился бы. Минимальный buy-in — хотя бы на два
 * больших блайнда: иначе игрок не ставит даже блайнды своей первой раздачи.
 */
export const POKER_MIN_BIG_BLIND = 2;
export const POKER_MIN_BUYIN_BB = 2;

/**
 * Блэкджек: лимиты ставки на руку задаёт создатель стола. Меньше двух 3:2
 * вырождается в 1:1 — блэкджек на ставке в одну монету платил бы как обычный
 * выигрыш. Минимальный buy-in — хотя бы на одну минимальную ставку.
 */
export const BLACKJACK_MIN_BET = 2;
