'use client';

import type { ReactNode } from 'react';
import { AuthGuard } from '@/features/auth';
import { OnboardingProvider, TourOverlay } from '@/features/onboarding';
import { TopNav } from '@/widgets/top-nav';

/**
 * Оболочка приложения: рейка разделов и защита от неавторизованного входа.
 *
 * Группа `(app)` в имени каталога — скобки, а не сегмент пути: она собирает
 * пять разделов под общий макет, но в адресе не появляется, и раздел остаётся
 * `/tags`, а не `/app/tags`.
 *
 * Рейка стоит СНАРУЖИ защиты: она ни от какой сессии не зависит и известна
 * ещё до первого запроса, а гасла вместе со всем остальным.
 *
 * Своей заглушки у оболочки нет, и это намеренно. Настоящий гейт —
 * `frontend/middleware.ts`, он отрабатывает раньше, на edge, и досюда
 * долетают только запросы с кукой сессии. AuthGuard внутри — не второй
 * гейт, а реакция на её потерю уже после захода (см. его комментарий);
 * ждать здесь нечего, каждая полная загрузка страницы просто идёт со
 * своими заглушками на местах своих чисел (см. `refreshSession`).
 *
 * Прокрутка — документа, а не внутренних панелей: страница-гроссбух кончается
 * там, где кончаются записи, и кривая может выйти в край вьюпорта (см. .bleed).
 * Возврат наверх при переходе между разделами делает сам роутер.
 */
export default function AppLayout({ children }: { children: ReactNode }) {
  return (
    <OnboardingProvider>
      <TopNav />
      <AuthGuard>{children}</AuthGuard>
      {/* Обучение — последним слоем и снаружи защиты: рейка, которую оно
          подсвечивает первым шагом, тоже стоит снаружи. Провайдер обнимает
          и её, потому что «Обучение заново» живёт в меню профиля. Сюда без
          куки сессии не попасть — гейт отработал раньше, на edge. */}
      <TourOverlay />
    </OnboardingProvider>
  );
}
