/**
 * Игры раздела «Турниры». Каталог — статический список, а не ответ сервера: игра
 * — это код и страница, которых на сервере не создать, а сервер о каталоге ничего
 * знать не обязан. Новая игра — запись здесь, тексты в `tournaments.games.<id>` и
 * своя страница под `/tournaments/<id>`; страница каталога, шапка и валюта не
 * меняются.
 *
 * Задуманы покер, блэкджек и торговля; в работе только торговля, поэтому других
 * записей нет — заглушек «скоро» на несуществующие игры каталог не рисует.
 */
export type Game = {
  id: 'trading';
  /** Адрес страницы игры. */
  href: string;
  /**
   * Страница игры уже есть. Пока нет — карточка стоит в каталоге, но ссылкой не
   * является: переход в несуществующий адрес хуже честного «скоро».
   */
  available: boolean;
};

export const GAMES: readonly Game[] = [
  { id: 'trading', href: '/tournaments/trading', available: true },
];
