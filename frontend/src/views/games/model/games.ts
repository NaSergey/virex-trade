/**
 * Игры раздела. Каталог — статический список, а не ответ сервера: игра — это
 * код и страница, которых на сервере не создать, а сервер о каталоге ничего
 * знать не обязан. Новая игра — запись здесь, тексты в `games.items.<id>`,
 * картинка в `public/assets/games/` и своя страница под `/games/<id>`;
 * витрина, шапка и валюта не меняются.
 *
 * Ненаписанные игры стоят в витрине с меткой «Скоро» и ссылками не являются.
 * Раздел — каталог, а не одна игра, и витрина из одной карточки читается не
 * как «пока одна игра», а как «раздел недоделан»; при этом обещание конкретной
 * игры без срока честнее пустого места, которое ничего не объясняет.
 *
 * Порядок — порядок карточек на витрине: раскладка сетки идёт по нему же, и
 * хранить его отдельным полем значит завести второй источник того же знания,
 * способный разойтись с первым.
 */
export type GameId = 'blackjack' | 'poker' | 'jetpack' | 'trading';

/**
 * Чипы под описанием — то, что игра обещает форматом: с кем играют и чем это
 * кончается. Ключи, а не готовые подписи: те же слова нужны на двух языках, а
 * набор у игр пересекается.
 */
export type GameTag = '1v1' | 'pvp' | 'tournaments' | 'ratings' | 'fast' | 'multiplayer';

/**
 * Акцент игры. Задаёт цвет свечения под карточкой и её рамки под курсором —
 * то есть ровно то, что и так светится на самой картинке. Собственного тона
 * подложки у карточек нет: цветные подложки на каждую игру уже пробовали, и
 * витрина распадалась на четыре чужих друг другу куска.
 */
export type GameAccent = 'green' | 'red' | 'purple';

/** Сцены, нарисованные кодом, — `views/games/components/<Name>Scene.tsx`. */
export type GameScene = 'trading' | 'poker' | 'blackjack' | 'jetpack';

export type Game = {
  id: GameId;
  /** Адрес страницы игры. */
  href: string;
  /**
   * Страница игры уже есть. Пока нет — карточка стоит в витрине, но ссылкой не
   * является: переход в несуществующий адрес хуже честного «скоро».
   */
  available: boolean;
  accent: GameAccent;
  tags: GameTag[];
  /**
   * Снимок карточки: `public/assets/games/<id>.webp`, 384×514. Пусто — значит
   * карточка рисует сцену кодом (см. `scene`).
   */
  image?: string;
  /**
   * Сцена вместо снимка — SVG, нарисованный кодом. У торговли потому, что
   * свечи это данные, и снимок рынка, которого не было, обещал бы конкретную
   * историю цены. У покера и блэкджека потому, что снимок не двигается, а
   * карты и фишки должны — в покое и под курсором. У джетпака по той же
   * причине: ракета летит, пламя бьёт, множитель растёт.
   */
  scene?: GameScene;
};

