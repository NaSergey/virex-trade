/**
 * Множители на плашках сцены джетпака под курсором. Пока курсор на карточке,
 * каждое число растёт от своего значения к большему; ушёл курсор — числа
 * возвращаются к своим. Хук (`useMultiplierRoll`) только двигает положение и
 * подставляет результат в текст на каждом кадре.
 *
 * Положение `s` — 0 у своего значения, 1 у значения под курсором — идёт по
 * времени ровно, а число — по логарифмической шкале между ними: растёт
 * экспонентой, медленно в начале и всё быстрее к концу, как множитель
 * crash-игры.
 */

/** Подпись множителя: одна цифра после точки, как на плашках. */
export const formatMultiplier = (v: number) => `${v.toFixed(1)}x`;

/** Подпись при положении `s` между своим значением `from` и значением под курсором `to`. */
export function multiplierAt(from: number, to: number, s: number) {
  const k = Math.min(1, Math.max(0, s));
  return formatMultiplier(from * (to / from) ** k);
}

/**
 * Положение через `dt` мс движения к цели `target`, если весь ход занимает
 * `full` мс. Движение идёт от текущего положения, поэтому курсор, ушедший на
 * середине роста, разворачивает число оттуда, где оно было, без скачка.
 */
export function stepToward(s: number, target: 0 | 1, dt: number, full: number) {
  const d = dt / full;
  return target ? Math.min(1, s + d) : Math.max(0, s - d);
}
