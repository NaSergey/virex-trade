'use client';

import type { ReactNode } from 'react';

/**
 * Шапка страницы: название, одна строка о том, что здесь считается, и — справа
 * на той же линии — управление, относящееся ко всей странице целиком.
 *
 * Подзаголовок необязателен по разметке, но обязателен по смыслу везде, где
 * страницу можно принять не за то: «Рынок» без пояснения читается как «мой
 * рынок». Поэтому он стоит рядом с названием, а не отдельным абзацем ниже.
 *
 * Правая половина — слот, а не проп с кнопкой: на разных страницах туда встают
 * разные вещи (тумблер инструмента, сброс условий), и общего у них только
 * место.
 */
export function PageHead({
  title,
  lede,
  children,
}: {
  title: ReactNode;
  lede?: ReactNode;
  /** Управление страницей — встаёт справа, на одной линии с названием. */
  children?: ReactNode;
}) {
  return (
    <div className="pagehead">
      <div>
        <h1>{title}</h1>
        {lede != null && <p className="lede">{lede}</p>}
      </div>
      {children}
    </div>
  );
}
