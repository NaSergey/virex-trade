"use client";

import * as React from "react";
import { cn } from "@/shared/lib/utils/css";

const Table = React.forwardRef<
  HTMLTableElement,
  React.HTMLAttributes<HTMLTableElement>
>(({ className, ...props }, ref) => (
  // h-full is load-bearing: without it, this div has no bounded height of
  // its own, so it just grows to fit every row and `overflow-auto` never
  // has anything to scroll — inside a fixed-height panel (e.g. Lab's trade
  // list), rows past what fits get clipped by an ancestor's overflow-hidden
  // with no way to reach them at all, not just a hidden scrollbar.
  <div className="scrollbar-thin relative h-full w-full overflow-auto">
    <table
      ref={ref}
      className={cn("w-full caption-bottom text-sm", className)}
      {...props}
    />
  </div>
));
Table.displayName = "Table";

