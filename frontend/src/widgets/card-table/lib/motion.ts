import type { SeatPoint } from './layout';

/**
 * Хореография стола. Все движения идут от крупье и к нему: колода стоит
 * вверху сукна, оттуда летят карты, туда же уходят сброшенные; ставки
 * собираются в центр, выигрыш уезжает к месту.
 *
 * Числа — одна шкала на весь стол и на обе игры: соседние движения
 * складываются во фразу (собрал ставки → открыл карту → заплатил), и
 * разъехавшиеся длительности читались бы рывками. Длительности продублированы
 * в globals.css (блок «СТОЛ КАРТОЧНЫХ ИГР: ДВИЖЕНИЕ»).
 */
/** Колода — во главе стола, у верхнего бортика: место над ней ни за кем не закреплено (см. `slotOf`). */
export const DEALER: SeatPoint = { x: 50, y: 14 };
/** Центр сукна: банк покера, куда съезжают ставки. */
export const CENTER: SeatPoint = { x: 50, y: 41 };

/** Шаг между картами при раздаче — по кругу, как сдаёт живой крупье. */
export const DEAL_STEP = 110;
/** Полёт карты от колоды до места. */
export const DEAL_FLY = 380;
/** Переворот карты лицом вверх. */
export const FLIP = 260;
/** Ставки съезжают со своих мест. */
export const COLLECT = 360;
/** Выигрыш летит к месту. */
export const WIN_FLY = 520;

/** Смещение от точки `to` к точке `from` — в долях сцены (`cqw`/`cqh`). */
export function offsetFrom(from: SeatPoint, to: SeatPoint) {
  return { dx: `${from.x - to.x}cqw`, dy: `${from.y - to.y}cqh` };
}
