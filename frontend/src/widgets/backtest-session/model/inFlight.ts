/**
 * Пометки прокрутки «исполнение уже отправлено» (ордер на вход, закрытие
 * позиции, лимит закрытия): пока запрос в пути и сессия не перечитана, уровень
 * второй раз не срабатывает.
 *
 * Успех пометку не снимает — ордер или позицию сервер уже снял, а снимок
 * сессии догонит. **Отказ снимает**, и уровень снова проверяется на касании:
 * раньше пометка жила до перезагрузки страницы, и ордер, исполнение которого
 * упало на сети или 5xx, оставался на сервере и на графике, а цена шла сквозь
 * него («залипшая лимитка», QA 2026-10-23). Безнадёжные отказы сервер снимает
 * вместе с ордером сам — повторять нечего.
 *
 * `maxFailures` — сколько отказов подряд терпеть, прежде чем оставить уровень
 * помеченным: постоянная ошибка (бот держит лонг, сессия кончилась) иначе слала
 * бы запрос на каждом тике. У закрытий предела нет — стоп обязан проверяться.
 */
export function createInFlight(maxFailures = Number.POSITIVE_INFINITY) {
  const pending = new Set<string>();
  const failures = new Map<string, number>();
  return {
    has: (id: string) => pending.has(id),
    track(id: string, sent: Promise<unknown>) {
      pending.add(id);
      sent.catch(() => {
        const n = (failures.get(id) ?? 0) + 1;
        failures.set(id, n);
        if (n < maxFailures) pending.delete(id);
      });
    },
  };
}

export type InFlight = ReturnType<typeof createInFlight>;
