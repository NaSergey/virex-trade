import { bucketStart, MINUTE, type Candle } from './candles';

/**
 * Чистые функции эфирного источника свечей. В отличие от прокрутки, где
 * будущее просто ещё не показано, здесь его физически нет: последняя минутка
 * прилетает снова и снова, пока не закроется.
 */

/**
 * Слияние минуток с живым хвостом.
 *
 * Хвост приходит раз в две секунды и всегда содержит уже известные минутки,
 * последняя из которых ещё формируется. Свежая версия минутки ЗАМЕЩАЕТ
 * прежнюю по времени открытия — дописывание дало бы десятки свечей на одну
 * минуту.
 *
 * Разрыв (вкладка спала) не заполняется: выдуманная свеча выглядела бы как
 * настоящая, а дыра видна и её догружает вызывающий.
 */
export function mergeMinutes(prev: Candle[], tail: Candle[]): Candle[] {
  if (tail.length === 0) return prev;
  const byTime = new Map<number, Candle>();
  for (const m of prev) byTime.set(m.t, m);
  for (const m of tail) byTime.set(m.t, m);
  return [...byTime.values()].sort((a, b) => a.t - b.t);
}

/**
 * Граница между хранилищем и минутками: правее неё свечи таймфрейма собираются
 * из минуток, левее — берутся закрытыми из `/api/market-data/candles`.
 *
 * Это конец последней СОХРАНЁННОЙ свечи, а не начало текущей. Синк свечей
 * отстаёт от биржи (он ходит раз в пятнадцать минут), и якорь по началу
 * текущей свечи оставил бы между хранилищем и ней дыру на всё отставание.
 * Правее начала текущей свечи якорь при этом не уезжает — она ещё формируется
 * и в хранилище ей взяться неоткуда.
 */
export function liveAnchor(closed: Candle[], tf: number, now: number): number {
  const current = bucketStart(now, tf);
  const last = closed.at(-1);
  if (!last) return current;
  return Math.min(last.t + tf * MINUTE, current);
}

/** Минутки одной монеты: лента эфира держит их вместе с монетой, к которой они относятся. */
export interface TaggedMinutes {
  symbol: string;
  rows: Candle[];
}

/**
 * Состояние ленты, если оно про эту монету; иначе null. Переключение монеты
 * не чистит состояние эффектом — оно просто перестаёт относиться к графику.
 */
export const ofSymbol = <T extends { symbol: string }>(state: T | null, symbol: string): T | null =>
  state?.symbol === symbol ? state : null;

/**
 * Слияние свежих минуток монеты: в ту же монету — `mergeMinutes`, в другую —
 * с чистого листа. Первый ответ после переключения монеты иначе дописался бы к
 * минуткам прежней, и график собрал бы свечи из двух рынков. Поздние ответы
 * прежней монеты сюда не доходят — их отсекает уборка эффекта ленты.
 */
export function mergeTagged(prev: TaggedMinutes, symbol: string, fresh: Candle[]): TaggedMinutes {
  return { symbol, rows: mergeMinutes(prev.symbol === symbol ? prev.rows : [], fresh) };
}

/**
 * Ближайший порог после момента `from`: перейдя его (`момент > порог`), часы
 * эфира обязаны обновить экран, а до него ничего видимого не меняется. Часы
 * тикают раз в 250 мс, но состояние трогают только на пороге: каждый тик
 * перерисовывал весь терминал, и на слабом устройстве это был пропущенный кадр
 * четыре раза в секунду (замер 2026-10-13).
 *
 * Пороги — всё, что читает момент на экране:
 * - свечи и цена: минутка видна, когда момент перешёл её начало, — граница
 *   минуты (`visibleUntil`, `lastPrice`; 4-часовая свеча — тоже граница минуты);
 * - позиции (`anchors` — их входы): «закрыть можно», когда момент перешёл
 *   вход, а возраст меняется каждую целую минуту от входа;
 * - конец сессии: `ended` — момент дошёл до `endTime`.
 *
 * Время входа и выхода действий берётся не отсюда, а точным моментом в миг
 * клика (`Replay.moment`).
 */
export function nextChange(from: number, anchors: readonly number[], endTime: number | null): number {
  let next = Math.ceil(from / MINUTE) * MINUTE;
  for (const a of anchors) {
    // Вход впереди: возраст сменится, когда момент дойдёт до входа (`>=`), а
    // «закрыть можно» — когда перейдёт его (`>`); первый порог — раньше на мс.
    const x = a > from ? a - 1 : a === from ? a : a + Math.ceil((from - a + 1) / MINUTE) * MINUTE - 1;
    if (x < next) next = x;
  }
  if (endTime != null && endTime - 1 >= from && endTime - 1 < next) next = endTime - 1;
  return next;
}
