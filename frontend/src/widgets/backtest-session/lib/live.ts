import { bucketStart, MINUTE, type Candle } from './candles';

/**
 * Чистые функции эфирного источника свечей. В отличие от прокрутки, где
 * будущее просто ещё не показано, здесь его физически нет: последняя минутка
 * прилетает снова и снова, пока не закроется.
 */

/**
 * Слияние минуток с живым хвостом.
 *
 * Хвост приходит раз в две секунды и всегда содержит уже известные минутки,
 * последняя из которых ещё формируется. Свежая версия минутки ЗАМЕЩАЕТ
 * прежнюю по времени открытия — дописывание дало бы десятки свечей на одну
 * минуту.
 *
 * Разрыв (вкладка спала) не заполняется: выдуманная свеча выглядела бы как
 * настоящая, а дыра видна и её догружает вызывающий.
 */
export function mergeMinutes(prev: Candle[], tail: Candle[]): Candle[] {
  if (tail.length === 0) return prev;
  const byTime = new Map<number, Candle>();
  for (const m of prev) byTime.set(m.t, m);
  for (const m of tail) byTime.set(m.t, m);
  return [...byTime.values()].sort((a, b) => a.t - b.t);
}

/**
 * Граница между хранилищем и минутками: правее неё свечи таймфрейма собираются
 * из минуток, левее — берутся закрытыми из `/api/market-data/candles`.
 *
 * Это конец последней СОХРАНЁННОЙ свечи, а не начало текущей. Синк свечей
 * отстаёт от биржи (он ходит раз в пятнадцать минут), и якорь по началу
 * текущей свечи оставил бы между хранилищем и ней дыру на всё отставание.
 * Правее начала текущей свечи якорь при этом не уезжает — она ещё формируется
 * и в хранилище ей взяться неоткуда.
 */
export function liveAnchor(closed: Candle[], tf: number, now: number): number {
  const current = bucketStart(now, tf);
  const last = closed.at(-1);
  if (!last) return current;
  return Math.min(last.t + tf * MINUTE, current);
}
