'use client';

import { W } from './model/geometry';
import { Skeleton } from '@/shared/ui/Skeleton';

/**
 * Место кривой, пока её нечем нарисовать.
 *
 * Раньше здесь стоял пустой холст с одной волосяной риской посередине — и на
 * тёмном листе это была просто дыра в треть экрана: ни следа того, что тут
 * что-то будет. Теперь место занято той же краской, что и все остальные
 * заглушки продукта, только тише: прямоугольник в полную силу перевесил бы
 * собой весь лист.
 *
 * Прямоугольник, а не подобие кривой: у кривой есть направление, а направление
 * — это и есть ответ, за которым человек пришёл. Нарисовать его до ответа
 * нельзя, а нарисовать «примерно горизонтальную» — значит соврать, что итог
 * около нуля.
 *
 * Мерку холста задаёт невидимый svg с тем же `viewBox`, что и у настоящей
 * кривой: высота получается ровно та, что займут данные, при любой ширине
 * экрана. Своей высотой в пикселях этого не добиться — холст масштабируется по
 * ширине того места, куда его поставили.
 */
export function EquityChartSkeleton({ height = 300 }: { height?: number }) {
  return (
    <div style={{ position: 'relative' }} aria-hidden>
      <svg
        viewBox={`0 0 ${W} ${height}`}
        style={{ display: 'block', width: '100%', height: 'auto', visibility: 'hidden' }}
      />
      {/* Обёртка держит место, краска заполняет её целиком. Своей высотой
          заглушка этого не умеет: `.skel` объявляет height: 12px, и на
          абсолютно спозиционированном узле эта высота сильнее растяжки по
          inset — холст в треть экрана выходил полоской в двенадцать пикселей. */}
      <div style={{ position: 'absolute', inset: 0 }}>
        <Skeleton as="span" flush height="100%" className="skel-canvas" />
      </div>
    </div>
  );
}
