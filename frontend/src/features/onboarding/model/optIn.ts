/**
 * Согласие на обучение — одно решение на весь продукт, а не на раздел.
 *
 * Отдельно от `seen.ts` (кто из туров уже пройден) намеренно: `seen` копится
 * тур за туром по мере того, как человек их проходит, а это — единственный
 * вопрос, который задаётся один раз, до первого тура вообще. «Нет» здесь
 * обязано погасить туры на ВСЕХ пяти страницах разом, а не только на той, где
 * спросили; будь это полем внутри `seen`, «нет» пришлось бы отдельно
 * дописывать в список каждого раздела — и один пропущенный дал бы вопросу
 * всплыть заново там, где на него уже ответили.
 *
 * `localStorage`, по той же причине, что и у `seen`: бэкенд ради этого не
 * трогается, а другой браузер или чистка данных спросят заново — расплата
 * принята сознательно.
 */

export const ONBOARDING_OPT_IN_KEY = 'virex.onboarding.optIn';

/**
 * `null` — вопрос ещё не задавали (в том числе на сервере и до первого чтения
 * хранилища — тур по нему не запускается и вопрос не показывается, см.
 * комментарий `usePersistentValue`). `true` — «да», `false` — «нет».
 */
export function decodeOptIn(raw: string | null): boolean | null {
  if (raw === '1') return true;
  if (raw === '0') return false;
  return null;
}

export function encodeOptIn(value: boolean | null): string | null {
  if (value === null) return null;
  return value ? '1' : '0';
}
