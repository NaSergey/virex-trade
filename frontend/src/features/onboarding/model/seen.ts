import type { TourId } from './tours';

/**
 * Отметка «этот тур уже показан».
 *
 * `localStorage`, а не поле на аккаунте: бэкенд ради обучения не трогается.
 * Расплата принята сознательно — другой браузер, телефон, приватная вкладка
 * или чистка данных, и туры пойдут заново. Переезд на сервер, если он
 * понадобится, меняет только этот файл: остальная фича не знает, где лежит
 * отметка, и работает через функции ниже.
 *
 * Все пройденные туры лежат в ОДНОМ ключе списком, а не по ключу на тур. Это
 * не экономия места: `usePersistentValue` — единственный в проекте безопасный
 * способ читать хранилище прямо в разметке (он же решает вопрос SSR, см. его
 * комментарий), и он работает с одним ключом и примитивом. Пять ключей
 * потребовали бы пяти хуков или чтения в эффекте — а чтение в эффекте здесь
 * означало бы вспышку тура у того, кто его давно прошёл.
 */

export const TOURS_SEEN_KEY = 'virex.tours.seen';

/**
 * Как читать сырое значение. Отсутствие ключа — пустой список: человек не
 * видел ничего. Это НЕ то же самое, что `null` из `usePersistentValue`, —
 * там `null` означает «ещё не читали хранилище» (сервер, первый кадр
 * гидрации), и запускать по нему тур нельзя.
 */
export function decodeSeen(raw: string | null): string {
  return raw ?? '';
}

/** Пустой список стирает ключ, а не пишет пустую строку. */
export function encodeSeen(value: string | null): string | null {
  return value || null;
}

export function hasSeen(list: string, id: TourId): boolean {
  return list.split(',').includes(id);
}

export function withSeen(list: string, id: TourId): string {
  return hasSeen(list, id) ? list : [...list.split(',').filter(Boolean), id].join(',');
}
