'use client';

import {
  createContext,
  useCallback,
  useContext,
  useEffect,
  useMemo,
  useState,
  type ReactNode,
} from 'react';
import { usePathname } from 'next/navigation';
import { usePersistentValue } from '@/shared/lib/storage/usePersistentValue';
import { decodeOptIn, encodeOptIn, ONBOARDING_OPT_IN_KEY } from './optIn';
import { decodeSeen, encodeSeen, hasSeen, withSeen, TOURS_SEEN_KEY } from './seen';
import { tourForPath, type Tour, type TourId } from './tours';

interface Active {
  tour: Tour;
  /** Индекс в `tour.steps` — по нему берётся якорь и ключ текста. */
  step: number;
  /** Место в счётчике «шаг N из M» — считается только по показываемым шагам. */
  position: number;
  total: number;
  /** Показываемых шагов до / после этого нет — от этого зависят кнопки. */
  first: boolean;
  last: boolean;
}

interface OnboardingValue {
  active: Active | null;
  /**
   * Вопрос «пройти обучение?» ещё не задавали вообще — ни на одной странице
   * продукта, — а на этой странице уже есть что показать. `null`, если
   * решение уже принято (в любую сторону) или у страницы своего тура нет.
   */
  prompt: Tour | null;
  /** Ответ «да» — решение общее на весь продукт, тур стартует с первого шага. */
  startTour: () => void;
  /** Ответ «нет» — туры гасятся на всех пяти страницах разом, не только здесь. */
  declineTour: () => void;
  next: () => void;
  prev: () => void;
  /**
   * «Пропустить» и Esc — уход из обучения целиком, на всех страницах разом.
   * То же самое, что ответ «нет» на общий вопрос: разделу это решение не
   * принадлежит. Досмотренный до «Готово» тур закрывается не этим, а `next`.
   */
  dismiss: () => void;
  /** Пропустить текущий шаг, не отмечая тур: якорь не нашёлся. */
  skipStep: () => void;
  /** «Обучение заново» из меню профиля — минует вопрос, ведь его уже задали. */
  restart: () => void;
}

const Ctx = createContext<OnboardingValue | null>(null);

/**
 * Ближайший в сторону `dir` шаг, которому есть что показать: без якоря либо с
 * якорем, который сейчас в документе. `null` — таких больше нет.
 *
 * Проверка происходит В МОМЕНТ НАЖАТИЯ, а не ожиданием внутри шага, и это не
 * оптимизация. Пустой аккаунт не имеет ни кривой, ни открытых позиций — два
 * шага подряд без якоря; ожидание в каждом означало бы, что человек нажал
 * «Далее» и несколько секунд смотрит на затемнение, в котором ничего нет.
 * К третьему шагу тура страница давно догрузилась, поэтому отсутствие узла
 * здесь — это «нечего показывать», а не «ещё не приехало».
 *
 * Ожидание в useAnchorRect при этом остаётся: оно закрывает первый шаг тура
 * (страница ещё грузится) и узел, который появится позже.
 */
function showableStep(tour: Tour, from: number, dir: 1 | -1): number | null {
  for (let i = from; i >= 0 && i < tour.steps.length; i += dir) {
    const anchor = tour.steps[i].anchor;
    if (!anchor || document.querySelector(anchor)) return i;
  }
  return null;
}

/**
 * Состояние обучения.
 *
 * Идёт ли сейчас тур — не хранится, а ВЫВОДИТСЯ из пяти вещей: адреса,
 * списка пройденных туров, ответа на общий вопрос «пройти обучение?», того,
 * на каком шаге человек остановился, и того, поставил ли этот шаг `pos`.
 * Отсюда всё остальное поведение получается само, без единого эффекта:
 *
 * - **Спрос — один на весь продукт, а не на страницу.** Пока `optIn` не
 *   отвечен (`null`), тур ни на одной из пяти страниц не идёт — вместо
 *   первого встреченного показывается вопрос («пройти обучение?»). «Да»
 *   отвечает на него сразу за все страницы: `optIn` становится `true`, и с
 *   этого момента каждый непройденный раздел при заходе просто начинает свой
 *   тур сам, без повторных вопросов. «Нет» делает `optIn` равным `false` —
 *   и туры гаснут везде: условие ниже проверяет его, а не список пройденных,
 *   так что непройденные разделы не нужно помечать пройденными по одному.
 * - **Уход со страницы посреди тура** просто меняет адрес: тур перестаёт
 *   выводиться и исчезает с экрана, пройденным не считаясь.
 * - **Возврат в раздел** продолжает с того шага, где человек ушёл: `pos`
 *   привязан к id тура и переживает переход в соседний раздел и обратно.
 *
 * Хранение — через `usePersistentValue` (и `seen`, и `optIn`): он единственный
 * умеет читать `localStorage` прямо в разметке, не расходясь с серверным
 * рендером. До первого чтения оба отдают `null` — «неизвестно», и это не то
 * же самое, что «список пуст» / «ответ — нет»: по «неизвестно» ни тур, ни
 * вопрос не показываются, иначе человек, прошедший обучение месяц назад,
 * ловил бы вспышку карточки на каждой загрузке страницы.
 */
export function OnboardingProvider({ children }: { children: ReactNode }) {
  const pathname = usePathname();
  const [seen, setSeen] = usePersistentValue<string | null>(
    TOURS_SEEN_KEY,
    decodeSeen,
    null,
    encodeSeen,
  );
  const [optIn, setOptIn] = usePersistentValue<boolean | null>(
    ONBOARDING_OPT_IN_KEY,
    decodeOptIn,
    null,
    encodeOptIn,
  );
  const [pos, setPos] = useState<{ tourId: TourId; step: number } | null>(null);

  const tour = tourForPath(pathname);

  const active = useMemo<Active | null>(() => {
    if (!tour || seen === null || hasSeen(seen, tour.id)) return null;
    // Вопрос ещё не задан или ответ «нет» — ни один тур не идёт. Первый
    // случай снаружи виден как `prompt` (см. ниже), второй — как ничего.
    if (!optIn) return null;
    const step = pos?.tourId === tour.id ? pos.step : 0;
    // Шаг за пределами списка — так `skipStep` гасит тур, не записывая его
    // пройденным (см. его комментарий).
    if (step >= tour.steps.length) return null;

    /*
     * Счётчик считается по показанным шагам, а не по всем: у пустого аккаунта
     * нет ни кривой, ни открытых позиций, и сквозная нумерация прыгала бы с
     * «4 из 8» на «7 из 8» — на глаз это неотличимо от поломки.
     *
     * Пройденные шаги считаются по документу, а оставшиеся — целиком, как
     * есть. Сосчитать по документу и их было бы точнее ровно один раз из
     * десяти: на первом шаге тура страница ещё грузится, ни свода, ни журнала
     * в ней нет, и «Шаг 1 из 2» — первое, что человек видит в продукте, — тут
     * же превращается в «Шаг 2 из 6». Оптимистичный счёт даёт «1 из 8», а
     * когда пропуски обнаружатся, знаменатель один раз уменьшится. Убывающий
     * знаменатель читается как «оказалось короче», растущий — как поломка.
     */
    const shown = tour.steps
      .slice(0, step + 1)
      .filter((s) => !s.anchor || document.querySelector(s.anchor)).length;
    const position = Math.max(1, shown);

    return {
      tour,
      step,
      position,
      total: position + (tour.steps.length - step - 1),
      /*
       * Кнопки — по индексу, БЕЗ заглядывания в документ.
       *
       * Заглядывание тут было и стоило тура целиком. Этот расчёт выполняется
       * при смене адреса, то есть до того, как новая страница отрисована:
       * якорей второго и третьего шага в документе ещё нет, «дальше показывать
       * нечего» получалось истиной, и первый же шаг любого раздела предлагал
       * «Готово» вместо «Далее». Пересчитаться значению было не от чего —
       * появление узлов в документе не меняет ни адрес, ни шаг.
       *
       * Расплата известна и мала: если пропущены ХВОСТОВЫЕ шаги, на последнем
       * показанном будет написано «Далее», а нажатие закончит тур. Соврать в
       * подписи одной кнопки дешевле, чем зависеть от того, успела ли
       * отрисоваться страница.
       */
      first: step === 0,
      last: step + 1 >= tour.steps.length,
    };
  }, [tour, seen, optIn, pos]);

  /*
   * Вопрос показывается один раз за всё время жизни аккаунта: на первой же
   * странице, у которой есть тур и который ещё не пройден, при условии, что
   * `optIn` — `null` (решения не было ни в одну сторону). Открытие второй
   * такой страницы после ответа его уже не покажет: `optIn` перестал быть
   * `null` вне зависимости от того, что ответили.
   */
  const prompt = tour && seen !== null && !hasSeen(seen, tour.id) && optIn === null ? tour : null;

  /**
   * «Да» на общий вопрос. Тур ЭТОЙ страницы стартует сразу — его и показывала
   * карточка с вопросом; остальные разделы начнут свои туры сами при заходе,
   * без нового вопроса (см. условие `active` выше).
   */
  const startTour = useCallback(() => {
    setOptIn(true);
    if (tour) setPos({ tourId: tour.id, step: 0 });
  }, [tour, setOptIn]);

  /**
   * «Нет» на общий вопрос — гасит туры на всех пяти страницах разом, а не
   * только на этой. Список пройденных (`seen`) здесь ни при чём: `active` и
   * сам `prompt` проверяют именно `optIn`, а не то, помечен ли раздел
   * пройденным, так что подряд метить все пять разделов не нужно.
   */
  const declineTour = useCallback(() => {
    setOptIn(false);
  }, [setOptIn]);

  /*
   * «Пропустить» и Esc — выход из ОБУЧЕНИЯ, а не из тура этого раздела.
   *
   * Раньше здесь стояло `withSeen(seen, active.tour.id)` — помечался
   * пройденным один текущий раздел. В связке с «Обучением заново», которое
   * очищает `seen` целиком, это давало ровно то, за что ругаются: человек
   * жал «Пропустить» на Обзоре, шёл в Теги — и получал тур заново, потом на
   * Аналитике, потом на Рынке, и так пять раз подряд. Отказ, который надо
   * повторить пять раз, отказом не является.
   *
   * Поэтому гасится `optIn`, тот же флаг, что и у ответа «нет» на общий
   * вопрос: одно решение на весь продукт. Вернуть обучение можно там же, где
   * и всегда, — «Обучение заново» в меню профиля.
   *
   * «Готово» на последнем шаге сюда НЕ ходит: его берёт `next`, и оно
   * помечает пройденным именно этот раздел, оставляя остальные. Это разные
   * вещи: «я досмотрел» и «не показывай мне это».
   */
  const dismiss = useCallback(() => {
    setOptIn(false);
  }, [setOptIn]);

  const next = useCallback(() => {
    if (!active) return;
    const target = showableStep(active.tour, active.step + 1, 1);
    if (target === null) {
      setSeen(withSeen(seen ?? '', active.tour.id));
      return;
    }
    setPos({ tourId: active.tour.id, step: target });
  }, [active, seen, setSeen]);

  const prev = useCallback(() => {
    if (!active) return;
    const target = showableStep(active.tour, active.step - 1, -1);
    if (target !== null) setPos({ tourId: active.tour.id, step: target });
  }, [active]);

  /*
   * Якорь шага не нашёлся — идём дальше, но тур пройденным НЕ отмечаем, пока
   * человек не увидел хотя бы один шаг.
   *
   * Разница с `next` существенна и стоила бы обучения целиком. Шаг 0
   * настроек — форма ключей, а она приезжает после ответа сервера: если
   * ответ задержался дольше, чем хук ждёт якорь, тур молча пробежал бы все
   * свои шаги и записался пройденным, ни разу не показавшись. Условие
   * `step > 0` отличает «человек дошёл сюда и дальше нечего показывать» от
   * «страница ещё не приехала»: во втором случае тур просто не идёт и
   * попробует ещё раз при следующем заходе.
   */
  const skipStep = useCallback(() => {
    if (!active) return;
    const target = showableStep(active.tour, active.step + 1, 1);
    if (target === null) {
      if (active.step > 0) setSeen(withSeen(seen ?? '', active.tour.id));
      else setPos({ tourId: active.tour.id, step: active.tour.steps.length });
      return;
    }
    setPos({ tourId: active.tour.id, step: target });
  }, [active, seen, setSeen]);

  /*
   * Пустая строка, а не `null`.
   *
   * `null` в этом хранилище означает «ещё не читали» — состояние сервера и
   * первого кадра гидрации, по которому тур не запускается. Записав его
   * руками, «Обучение заново» стирало отметки и тут же само себя гасило: ключ
   * из хранилища исчезал, но в памяти оставалось «неизвестно», и ни один тур
   * не начинался до перезагрузки страницы. Пустая строка — это «не видел
   * ничего», и ключ она из хранилища всё равно убирает (см. encodeSeen).
   */
  const restart = useCallback(() => {
    setSeen('');
    // Нажатие пункта меню — само по себе согласие: общий вопрос он минует
    // (`optIn` сразу `true`), а не только вопрос текущей страницы. Тур этой
    // страницы стартует сразу; туры остальных четырёх разделов становятся
    // непройденными и при заходе начнутся сами, без карточки-вопроса — она
    // ведь уже отвечена, пусть и из меню, а не с карточки.
    setOptIn(true);
    setPos(tour ? { tourId: tour.id, step: 0 } : null);
  }, [setSeen, setOptIn, tour]);

  // Клавиши — на документе, а не на карточке: фокус может уйти на кнопку
  // внутри неё, и обработчик на конкретном узле перестал бы срабатывать.
  // Esc здесь не перехватывается — его берёт Radix у карточки и зовёт dismiss.
  useEffect(() => {
    if (!active) return;
    const onKey = (e: KeyboardEvent) => {
      if (e.key === 'ArrowRight') next();
      if (e.key === 'ArrowLeft') prev();
    };
    document.addEventListener('keydown', onKey);
    return () => document.removeEventListener('keydown', onKey);
  }, [active, next, prev]);

  const value = useMemo<OnboardingValue>(
    () => ({ active, prompt, startTour, declineTour, next, prev, dismiss, skipStep, restart }),
    [active, prompt, startTour, declineTour, next, prev, dismiss, skipStep, restart],
  );

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useOnboarding(): OnboardingValue {
  const value = useContext(Ctx);
  if (!value) throw new Error('useOnboarding вне OnboardingProvider');
  return value;
}

export type { TourId };
