/**
 * Выходы из-за стола, которые ещё не долетели до сервера.
 *
 * Уход со страницы стола — это ещё и «встать» (`useLeaveOnExit`), и лобби,
 * куда человек обычно и уходит, открывается в тот же момент. Спросив списки
 * столов раньше, чем сервер принял выход, лобби рисовало устаревшее — стол,
 * из-за которого только что встали, ещё в «Моих», — а через миг, когда выход
 * доходил, перерисовывало всё заново. Страница дёргалась дважды подряд.
 *
 * Поэтому списки столов сначала дожидаются выходов, начатых до них, — и
 * первый же ответ уже верный. Выход регистрируется сразу при уходе со
 * страницы стола, до того как лобби начнёт что-либо запрашивать.
 */
const exits = new Set<Promise<void>>();

export function trackExit(exit: Promise<void>) {
  exits.add(exit);
  // `then` с обработчиком и на отказ: `finally` пробросил бы отказ дальше, и
  // упавший выход стал бы необработанной ошибкой.
  const forget = () => void exits.delete(exit);
  exit.then(forget, forget);
}

/** Дождаться всех выходов, начатых к этому моменту. Ошибка выхода список не роняет. */
export async function afterExits(): Promise<void> {
  if (exits.size === 0) return;
  await Promise.allSettled([...exits]);
}
